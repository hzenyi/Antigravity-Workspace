def main():
    with open('downloads/sub_items.json', 'r', encoding='utf-8') as f:
        items = json.load(f)

    print(f"Total subtitle items to build: {len(items)}")
    
    srt_output_lines = []
    bilingual_output_lines = []
    
    for item in items:
        idx = item['index']
        timing = item['timing']
        ko_text = item['text']
        
        zh_text = ZH_EXACT.get(idx, "")
        if not zh_text:
            zh_text = "（通訊原理實作解析）"
        
        # 單語繁體中文字幕
        srt_output_lines.append(f"{idx}\n{timing}\n{zh_text}\n")
        # 雙語對照字幕
        bilingual_output_lines.append(f"{idx}\n{timing}\n{zh_text}\n{ko_text}\n")

    # 1. 輸出至 downloads/ 與影片同名：USB_and_UART_MCU_Intro_Ep10.srt
    # 這是所有播放器 (PotPlayer, VLC, Windows Media Player) 自動掛載字幕的第一順位！
    path_auto = 'downloads/USB_and_UART_MCU_Intro_Ep10.srt'
    with open(path_auto, 'w', encoding='utf-8') as f:
        f.write('\n'.join(srt_output_lines).strip() + '\n')
    print(f"✅ Generated: {path_auto}")

    # 2. 輸出至 downloads/ 語言後綴：USB_and_UART_MCU_Intro_Ep10.zh-TW.srt
    path_zhtw = 'downloads/USB_and_UART_MCU_Intro_Ep10.zh-TW.srt'
    with open(path_zhtw, 'w', encoding='utf-8') as f:
        f.write('\n'.join(srt_output_lines).strip() + '\n')
    print(f"✅ Generated: {path_zhtw}")

    # 3. 依專案規範備份至 subtitles/ 目錄
    path_sub_zhtw = 'subtitles/USB_and_UART_MCU_Intro_Ep10.zh-TW.srt'
    with open(path_sub_zhtw, 'w', encoding='utf-8') as f:
        f.write('\n'.join(srt_output_lines).strip() + '\n')
    print(f"✅ Generated: {path_sub_zhtw}")

    # 4. 韓中雙語字幕備份至 subtitles/ 目錄
    path_sub_bi = 'subtitles/USB_and_UART_MCU_Intro_Ep10.bilingual.srt'
    with open(path_sub_bi, 'w', encoding='utf-8') as f:
        f.write('\n'.join(bilingual_output_lines).strip() + '\n')
    print(f"✅ Generated: {path_sub_bi}")

if __name__ == '__main__':
    main()
